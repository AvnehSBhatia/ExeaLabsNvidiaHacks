"""Write the README to-do from site/data/todo.json, the single record of what is built and what is left.

    python scripts/render_todo_readme.py          # rewrite the block between the todo markers in README.md
    python scripts/render_todo_readme.py --check  # exit 1 if README.md is not what the JSON would give

Edit site/data/todo.json, then run this, so the README and the website cannot disagree.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
START, END = (
    "<!-- todo:start (generated by scripts/render_todo_readme.py from site/data/todo.json) -->",
    "<!-- todo:end -->",
)
WORD = {"done": "Shipped", "review": "In review", "todo": "Next", "blocked": "Blocked"}
SIZE = {"S": "S", "M": "M", "L": "L"}


def refs(it: dict) -> str:
    out = [f"#{n}" for n in it.get("pr") or []]
    if it.get("issue") and not out:
        out.append(f"issue #{it['issue']}")
    return ", ".join(out) or "none"


def who(it: dict) -> str:
    return ", ".join(f"@{a}" if a != "Claude Code" else a for a in it.get("authors") or []) or "unassigned"


def cell(s: str) -> str:
    return s.replace("|", "\\|")


def render(todo: dict) -> str:
    c, prs = todo["counts"], todo["prs"]
    L = [
        START,
        "",
        f"As of {todo['as_of']}: **{c['done']}** shipped, **{c['review']}** in review, **{c['todo']}** next, "
        f"**{c['blocked']}** blocked, of **{c['total']}** items. {prs['merged']} pull requests merged, {prs['open']} open. "
        "The list lives in `site/data/todo.json`. A row is shipped only when its pull request is merged on `main`.",
        "",
        "Sizes: S under half a day, M about a day, L several days. Priority: **must** (the demo or the core claim breaks "
        'without it), **should**, nice. Anything that needs real data reports "not measured" until the blocked rows land.',
        "",
    ]
    for g in todo["groups"]:
        L += [f"### {g['title']} ({len(g['items'])})", "", g["blurb"], ""]
        if g["id"] == "shipped":
            L += ["| id | what | PRs | who |", "|---|---|---|---|"]
            L += [f"| {it['id']} | {cell(it['title'])} | {refs(it)} | {who(it)} |" for it in g["items"]]
        else:
            L += ["| id | what | size | priority | status | PRs or issue | who |", "|---|---|---|---|---|---|---|"]
            for it in g["items"]:
                what = cell(it["title"]) + (f" {cell(it['note'])}" if it.get("note") else "")
                L.append(
                    f"| {it['id']} | {what} | {it.get('size') or ''} | {it.get('priority') or ''} | "
                    f"{WORD[it['status']]} | {refs(it)} | {who(it)} |"
                )
        L.append("")
    sup, nm = todo.get("superseded"), todo.get("not_merged")
    if sup or nm:
        L += ["### Pull requests not merged as they are", ""]
        if sup:
            L.append(f"- {', '.join('#%d' % n for n in sup['prs'])}: {sup['note']}")
        if nm:
            L.append(f"- {', '.join('#%d' % n for n in nm['prs'])}: {nm['note']}")
        L.append("")
    L.append(END)
    return "\n".join(L)


def apply(readme: str, block: str) -> str:
    a, b = readme.index(START.split(" (")[0]), readme.index(END) + len(END)
    return readme[:a] + block + readme[b:]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    todo = json.loads((REPO / "site" / "data" / "todo.json").read_text(encoding="utf-8"))
    path = REPO / "README.md"
    old = path.read_text(encoding="utf-8")
    new = apply(old, render(todo))
    if a.check:
        if new != old:
            print("README.md to-do is out of date: run python scripts/render_todo_readme.py", file=sys.stderr)
            return 1
        return 0
    path.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
